import { Injectable, inject } from '@angular/core';
import { PagedResult, SortSpec } from '../../data-access/query.model';
import { DocumentQuery, DocumentRepository, NotificationQuery, NotificationRepository } from '../../data-access/repositories';
import { DEFAULT_EXPIRY_WARNING_DAYS } from '../../domain/document-status';
import { addDays } from '../../formatting/date-utils';
import { AppNotification, FleetDocument } from '../../models';
import { ClockService } from '../../services/clock.service';
import { toError } from '../supabase-client';
import { FilterBuilder, SupabaseCollection, eqIf } from '../supabase-collection';

@Injectable()
export class SupabaseDocumentRepository extends SupabaseCollection<FleetDocument, DocumentQuery> implements DocumentRepository {
  private readonly clock = inject(ClockService);

  protected readonly table = 'documents';
  protected readonly searchColumns = ['reference', 'title', 'issuer', 'file_name'];
  protected readonly defaultSort: SortSpec = { field: 'expiryDate', direction: 'asc' };
  protected override readonly emptyAsNull = ['expiryDate', 'fileName', 'fileSizeKb'];

  protected applyFilters(request: FilterBuilder, query: DocumentQuery): FilterBuilder {
    request = eqIf(eqIf(eqIf(request, 'type', query.type), 'entity_type', query.entityType), 'entity_id', query.entityId);
    // Status is derived from the expiry date, like expiryStatus() in document-status.ts.
    const today = this.clock.today();
    const warningLimit = addDays(today, DEFAULT_EXPIRY_WARNING_DAYS);
    switch (query.status) {
      case 'no_expiry':
        return request.is('expiry_date', null);
      case 'expired':
        return request.lt('expiry_date', today);
      case 'expiring':
        return request.gte('expiry_date', today).lte('expiry_date', warningLimit);
      case 'valid':
        return request.gt('expiry_date', warningLimit);
      default:
        return request;
    }
  }
}

/**
 * Notifications are generated by the database (refresh_my_notifications) and read through the
 * `notifications_feed` view, which adds the signed-in user's own read flag.
 */
@Injectable()
export class SupabaseNotificationRepository extends SupabaseCollection<AppNotification, NotificationQuery> implements NotificationRepository {
  private refreshed: Promise<void> | null = null;

  protected readonly table = 'notifications_feed';
  protected readonly searchColumns = ['params->>trip', 'params->>vehicle', 'params->>document', 'params->>driver', 'params->>workOrder'];
  protected readonly defaultSort: SortSpec = { field: 'createdAt', direction: 'desc' };

  protected applyFilters(request: FilterBuilder, query: NotificationQuery): FilterBuilder {
    request = eqIf(request, 'category', query.category);
    return query.unreadOnly ? request.eq('read', false) : request;
  }

  /** The first read of the session also generates any new notifications from the current data. */
  override async list(query?: NotificationQuery): Promise<PagedResult<AppNotification>> {
    await this.refreshOnce();
    return super.list(query);
  }

  override async all(): Promise<AppNotification[]> {
    await this.refreshOnce();
    return super.all();
  }

  async markRead(id: string, read = true): Promise<void> {
    const reads = this.client.from('notification_reads');
    const { error } = read
      ? await reads.upsert({ notification_id: id }, { onConflict: 'notification_id,user_id', ignoreDuplicates: true })
      : await reads.delete().eq('notification_id', id);
    if (error) throw toError(error);
    this.bump();
  }

  async markAllRead(): Promise<void> {
    const { error } = await this.client.rpc('mark_all_notifications_read');
    if (error) throw toError(error);
    this.bump();
  }

  /** Only owner / admin may delete (RLS); deletes go to the table, not the view. */
  override async delete(id: string): Promise<void> {
    const { error } = await this.client.from('notifications').delete().eq('id', id);
    if (error) throw toError(error);
    this.bump();
  }

  /** Notifications are produced by the database, never created or edited from the browser. */
  override create(): Promise<AppNotification> {
    return Promise.reject(new Error('Notifications are generated by the backend'));
  }

  override async update(id: string, changes: Partial<AppNotification>): Promise<AppNotification> {
    if (changes.read !== undefined) await this.markRead(id, changes.read);
    const notification = await this.getById(id);
    if (!notification) throw new Error(`Notification ${id} not found`);
    return notification;
  }

  private refreshOnce(): Promise<void> {
    this.refreshed ??= Promise.resolve(this.client.rpc('refresh_my_notifications')).then(({ error }) => {
      // Not fatal: the existing notifications are still shown.
      if (error) console.error(toError(error));
    });
    return this.refreshed;
  }
}

